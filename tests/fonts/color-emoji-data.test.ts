import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, it, expect } from 'vitest';
import * as colorEmoji from '../../fonts/noto-color-emoji-data.js';
import { buildDocumentPDFBytes } from '../../src/core/pdf-document.js';
import { openPdf } from '../../src/parser/pdf-reader.js';
import { CURATED_EMOJI } from '../../scripts/lib/curated-emoji.js';
import type { FontData, FontEntry } from '../../src/types/pdf-types.js';
import type { DocumentParams } from '../../src/types/pdf-document-types.js';

// Guards the committed curated colour-emoji data module
// (fonts/noto-color-emoji-data.js, generated by scripts/build-color-emoji-data.ts).

describe('noto-color-emoji-data module', () => {
    it('exports a valid colour FontData shape', () => {
        expect(colorEmoji.fontName).toBe('NotoColorEmoji-Regular');
        expect(typeof colorEmoji.ttfBase64).toBe('string');
        expect(colorEmoji.ttfBase64.length).toBeGreaterThan(1000);
        expect(colorEmoji.metrics.unitsPerEm).toBeGreaterThan(0);
        expect(Object.keys(colorEmoji.colorGlyphs).length).toBeGreaterThan(100);
        expect(Object.keys(colorEmoji.cmap).length).toBeGreaterThan(100);
    });

    it('bundles the expanded curated set (~1170) within the size budget', () => {
        // Expanded from 221 to ~850, then to 1167 (Misc S&P completion +
        // full Transport & Map) in v1.6.0.
        expect(CURATED_EMOJI.length).toBeGreaterThanOrEqual(1050);
        expect(CURATED_EMOJI.length).toBeLessThanOrEqual(1250);
        // No duplicates.
        expect(new Set(CURATED_EMOJI).size).toBe(CURATED_EMOJI.length);
        // Module stays within the npm-tarball budget (raised 4096 → 5120 KB
        // in v1.7.0 for the curated flag/ZWJ sequence set).
        const sizeKb = Buffer.byteLength(colorEmoji.ttfBase64) / 1024;
        expect(sizeKb).toBeLessThan(5120);
    });

    it('every curated codepoint maps to a colour glyph', () => {
        // Hard guarantee: the bundled cmap covers the WHOLE curated list, so
        // no curated emoji can ever regress to `.notdef` tofu. (The list is
        // pruned at build time of codepoints the font has no COLR glyph for.)
        for (const cp of CURATED_EMOJI) {
            const gid = colorEmoji.cmap[cp];
            expect(gid, `U+${cp.toString(16).toUpperCase()} missing from cmap`).toBeDefined();
            expect(colorEmoji.colorGlyphs[gid as number], `U+${cp.toString(16).toUpperCase()} has no colour glyph`).toBeDefined();
        }
    });

    it('every cmap entry resolves to a colour glyph with width metrics', () => {
        for (const [cpStr, gid] of Object.entries(colorEmoji.cmap)) {
            expect(colorEmoji.colorGlyphs[gid as number]).toBeDefined();
            expect(typeof colorEmoji.widths[gid as number] === 'number' || colorEmoji.metrics).toBeTruthy();
            void cpStr;
        }
    });

    it('covers the ranges the v1.6.0 expansion completed', () => {
        // The 15 codepoints that rendered as tofu in color-emoji-basic.pdf
        // before the Misc S&P / Transport & Map completion, plus a spot-check
        // of each restored range.
        const restored = [
            0x1f5a4, 0x1f525, 0x1f4af, 0x1f4aa, 0x1f697, 0x1f695, 0x1f68c,
            0x1f680, 0x1f6a2, 0x1f4f1, 0x1f4cc, 0x1f512, 0x1f511, 0x1f4b0,
            0x1f4b5,
            0x1f4c5, 0x1f50d, 0x1f550, 0x1f6d2, 0x1f6f8,
        ];
        for (const cp of restored) {
            const gid = colorEmoji.cmap[cp];
            expect(gid, `U+${cp.toString(16).toUpperCase()} missing from cmap`).toBeDefined();
            expect(colorEmoji.colorGlyphs[gid as number]).toBeDefined();
        }
        // Extended-A (U+1FA70-1FAFF) is documented as NOT bundled (CLI-only).
        expect(colorEmoji.cmap[0x1fa79]).toBeUndefined();
    });

    it('covers every emoji used by the colour-emoji showcase generator', () => {
        // Cross-check: scripts/generators/color-emoji-showcase.ts promises
        // "zero .notdef tofu" — hold it to that by asserting every emoji
        // codepoint in its source is in the bundled cmap.
        const src = readFileSync(
            fileURLToPath(new URL('../../scripts/generators/color-emoji-showcase.ts', import.meta.url)),
            'utf8',
        );
        const isEmojiBlock = (cp: number): boolean =>
            (cp >= 0x231a && cp <= 0x231b) || (cp >= 0x23e9 && cp <= 0x23fa) ||
            (cp >= 0x2600 && cp <= 0x27bf) || (cp >= 0x2b00 && cp <= 0x2bff) ||
            (cp >= 0x1f300 && cp <= 0x1faff);
        const used = new Set<number>();
        for (const ch of src) {
            const cp = ch.codePointAt(0) as number;
            if (isEmojiBlock(cp)) used.add(cp);
        }
        expect(used.size).toBeGreaterThan(50);
        // A codepoint is covered when the cmap maps it directly OR it only
        // ever appears as a component of a bundled sequence (flags/ZWJ, whose
        // ligature glyph renders the whole run — v1.7.0).
        const sequenceComponents = new Set<number>();
        const seqs = colorEmoji.sequences as NonNullable<FontData['sequences']> | null;
        if (seqs) {
            for (const [first, entries] of Object.entries(seqs)) {
                sequenceComponents.add(Number(first));
                for (const entry of entries) for (let k = 1; k < entry.length; k++) sequenceComponents.add(entry[k]);
            }
        }
        for (const cp of used) {
            const gid = colorEmoji.cmap[cp];
            if (gid === undefined) {
                expect(sequenceComponents.has(cp), `showcase uses U+${cp.toString(16).toUpperCase()} but it is neither in the bundled cmap nor part of a bundled sequence`).toBe(true);
                continue;
            }
            expect(colorEmoji.colorGlyphs[gid as number]).toBeDefined();
        }
    });

    it('maps common emoji codepoints to colour glyphs', () => {
        const grin = colorEmoji.cmap[0x1f600];
        expect(grin).toBeGreaterThan(0);
        expect(colorEmoji.colorGlyphs[grin]).toBeDefined();
        expect(colorEmoji.colorGlyphs[grin].layers.length).toBeGreaterThan(0);
    });

    it('renders colour emoji as Form XObjects in a document', () => {
        const fontData = colorEmoji as unknown as FontData;
        const entry: FontEntry = { fontData, fontRef: '/F3', lang: 'emoji' };
        const params: DocumentParams = {
            title: 'Colour Emoji Module',
            blocks: [{ type: 'paragraph', text: 'Hi \u{1F600} \u{2764} \u{1F44D} there' }],
            fontEntries: [entry],
        };
        const bytes = buildDocumentPDFBytes(params);
        const pdf = Buffer.from(bytes).toString('latin1');
        expect(pdf).toContain('/Subtype /Form');
        expect(pdf).toMatch(/\/CEm\d+ Do/);
        const doc = openPdf(bytes);
        expect(doc.pageCount).toBe(1);
    });

    // ── v1.7.0: bundled flag / ZWJ sequences ─────────────────────────

    describe('sequences table', () => {
        it('exports a codepoint-keyed sequences table', () => {
            expect(colorEmoji.sequences).toBeTruthy();
            const seqs = colorEmoji.sequences as NonNullable<FontData['sequences']>;
            expect(Object.keys(seqs).length).toBeGreaterThan(20);
        });

        it('every sequence entry resolves to a colour ligature glyph with a width', () => {
            const seqs = colorEmoji.sequences as NonNullable<FontData['sequences']>;
            for (const [firstCp, entries] of Object.entries(seqs)) {
                for (const entry of entries) {
                    const gid = entry[0];
                    expect(entry.length, `sequence at U+${Number(firstCp).toString(16)}`).toBeGreaterThanOrEqual(2);
                    expect(colorEmoji.colorGlyphs[gid], `lig gid ${gid} has no colour glyph`).toBeDefined();
                    expect(colorEmoji.widths[gid], `lig gid ${gid} has no width`).toBeDefined();
                }
            }
        });

        it('keeps entries longest-first per first-codepoint bucket', () => {
            const seqs = colorEmoji.sequences as NonNullable<FontData['sequences']>;
            for (const entries of Object.values(seqs)) {
                for (let i = 1; i < entries.length; i++) {
                    expect(entries[i - 1].length).toBeGreaterThanOrEqual(entries[i].length);
                }
            }
        });

        it('bundles the curated flags (FR, DE, JP, EU…) and ZWJ sets', () => {
            const seqs = colorEmoji.sequences as NonNullable<FontData['sequences']>;
            const has = (cps: readonly number[]): boolean => {
                const bucket = seqs[cps[0]];
                return Boolean(bucket?.some(e =>
                    e.length - 1 === cps.length - 1 && cps.slice(1).every((c, k) => e[1 + k] === c)));
            };
            expect(has([0x1F1EB, 0x1F1F7])).toBe(true); // 🇫🇷
            expect(has([0x1F1E9, 0x1F1EA])).toBe(true); // 🇩🇪
            expect(has([0x1F1EF, 0x1F1F5])).toBe(true); // 🇯🇵
            expect(has([0x1F1EA, 0x1F1FA])).toBe(true); // 🇪🇺
            expect(has([0x1F468, 0x200D, 0x1F4BB])).toBe(true); // 👨‍💻
            expect(has([0x1F3F4, 0x200D, 0x2620, 0xFE0F])).toBe(true); // 🏴‍☠️
        });

        it('keeps joiners and regional indicators OUT of the cmap', () => {
            // The "every cmap entry → colour glyph" invariant depends on it.
            expect(colorEmoji.cmap[0x200D]).toBeUndefined();
            expect(colorEmoji.cmap[0xFE0F]).toBeUndefined();
            expect(colorEmoji.cmap[0x1F1EB]).toBeUndefined();
        });

        it('renders a flag and a ZWJ sequence as single colour glyphs', () => {
            const fontData = colorEmoji as unknown as FontData;
            const entry: FontEntry = { fontData, fontRef: '/F3', lang: 'emoji' };
            const params: DocumentParams = {
                title: 'Sequences',
                blocks: [{ type: 'paragraph', text: 'Flags \u{1F1EB}\u{1F1F7} \u{1F1E9}\u{1F1EA} and \u{1F468}\u{200D}\u{1F4BB}' }],
                fontEntries: [entry],
            };
            const bytes = buildDocumentPDFBytes(params);
            const pdf = Buffer.from(bytes).toString('latin1');
            const doOps = pdf.match(/\/CEm\d+ Do/g) ?? [];
            // 2 flags + 1 technologist = 3 colour form draws.
            expect(doOps.length).toBeGreaterThanOrEqual(3);
            expect(openPdf(bytes).pageCount).toBe(1);
        });
    });
});
